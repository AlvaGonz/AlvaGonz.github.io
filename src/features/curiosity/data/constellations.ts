// Curated astronomical constellation catalog with J2000 celestial coordinates
// Right Ascension (RA) in degrees (0° - 360°), Declination (Dec) in degrees (-90° to +90°)

export interface CelestialStar {
  id: string;
  name: string;
  ra: number; // degrees [0, 360)
  dec: number; // degrees [-90, +90]
  mag: number; // apparent magnitude (smaller = brighter)
  color?: string; // hex color based on spectral type
  constellationId?: string;
}

export interface Constellation {
  id: string;
  name: string;
  latinName: string;
  season: 'All' | 'Spring' | 'Summer' | 'Autumn' | 'Winter';
  description: string;
  brightestStar: string;
  stars: CelestialStar[];
  lines: [string, string][]; // Pairs of star IDs forming the asterism
}

