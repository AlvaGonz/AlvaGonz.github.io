// Ambient stars across the sky to populate the cosmos with realistic density
export const AMBIENT_CELESTIAL_STARS: CelestialStar[] = Array.from({ length: 72 }).map((_, i) => {
  const ra = (i * 47 + 13) % 360;
  const dec = ((i * 31 + 17) % 150) - 60; // -60 to +90 degrees
  const mag = 2.5 + ((i * 7) % 25) / 10; // 2.5 to 5.0
  const colors = ['#ffffff', '#c7cee8', '#d0d34d', '#e0e7ff', '#fef08a'];
  return {
    id: `ambient_star_${i}`,
    name: `HD ${((i * 12345) % 99999) + 10000}`,
    ra,
    dec,
    mag,
    color: colors[i % colors.length],
  };
});
